"""Markdown reports: `report.md` per results dir, and the results table in the root README.

The README block sits between `<!-- eval-results:start -->` and `<!-- eval-results:end -->`;
replacing it is idempotent. When several results dirs are given, a model comparison table is
added (one column per results dir).
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

from caselens_evals.metrics import Scorecard

README = Path(__file__).resolve().parents[2] / "README.md"
REPORT_FILE = "report.md"
SCORES_FILE = "scores.json"
START = "<!-- eval-results:start -->"
END = "<!-- eval-results:end -->"


def _mark(passed: bool | None) -> str:
    return "n/a" if passed is None else ("pass" if passed else "FAIL")


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.1f}%"


def metrics_table(card: Scorecard) -> str:
    lines = ["| Metric | Target | Value | n | Result |", "| --- | --- | --- | --- | --- |"]
    for m in card.metrics:
        note = f" ({m.note})" if m.note else ""
        lines.append(f"| {m.name} | {m.target} | {m.display}{note} | {m.n} | {_mark(m.passed)} |")
    return "\n".join(lines)


def category_table(card: Scorecard) -> str:
    lines = [
        "| Category | n | Correctness | Citation recall | Citation precision | Hallucination |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for c in card.categories:
        lines.append(
            f"| {c.category} | {c.n} | {_pct(c.correctness)} | {_pct(c.citation_recall)} | "
            f"{_pct(c.citation_precision)} | {_pct(c.hallucination)} |"
        )
    return "\n".join(lines)


def comparison_table(cards: Sequence[tuple[str, Scorecard]]) -> str:
    head = "| Metric | Target | " + " | ".join(label for label, _ in cards) + " |"
    sep = "| --- | --- | " + " | ".join("---" for _ in cards) + " |"
    lines = [head, sep]
    for m in cards[0][1].metrics:
        cells = []
        for _, card in cards:
            other = next((x for x in card.metrics if x.key == m.key), None)
            cells.append("n/a" if other is None else f"{other.display} ({_mark(other.passed)})")
        lines.append(f"| {m.name} | {m.target} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def card_label(card: Scorecard, fallback: str) -> str:
    return ", ".join(card.models) or fallback


def summary_lines(card: Scorecard) -> list[str]:
    lines = [
        f"- Date: {card.date or 'n/a'}",
        f"- Agent model(s): {', '.join(card.models) or 'n/a'}",
        f"- Judge model(s): {', '.join(card.judge_models) or 'n/a'}",
        f"- Questions scored: {card.runs} ({card.failed_runs} failed runs), judged: {card.judged}",
        f"- CI gate (citation precision >= 95%): {'pass' if card.gate_passed else 'FAIL'}",
    ]
    lines += [f"- Note: {n}" for n in card.notes]
    return lines


def render_report(card: Scorecard, title: str) -> str:
    parts = [
        f"# CaseLens eval report: {title}",
        "",
        "SYNTHETIC DATA: the gold set and the demo case are fictional.",
        "",
        *summary_lines(card),
        "",
        "## Metrics",
        "",
        metrics_table(card),
        "",
        "## By category",
        "",
        category_table(card),
        "",
    ]
    return "\n".join(parts)


def readme_block(cards: Sequence[tuple[str, Scorecard]]) -> str:
    label, card = cards[0]
    parts = [
        START,
        f"Latest results (`evals/results/{label}`), generated by `python -m caselens_evals "
        "report --readme`.",
        "",
        *summary_lines(card),
        "",
        metrics_table(card),
        "",
        category_table(card),
    ]
    if len(cards) > 1:
        named = [(f"{card_label(c, lbl)} ({lbl})", c) for lbl, c in cards]
        parts += ["", "Model comparison:", "", comparison_table(named)]
    parts.append(END)
    return "\n".join(parts)


def replace_block(text: str, block: str) -> str:
    """Put `block` between the markers, adding an Evaluation section when they are missing."""
    if START in text and END in text:
        head, _, rest = text.partition(START)
        _, _, tail = rest.partition(END)
        return head + block + tail
    sep = "" if text.endswith("\n\n") else ("\n" if text.endswith("\n") else "\n\n")
    return f"{text}{sep}## Evaluation\n\n{block}\n"


def update_readme(cards: Sequence[tuple[str, Scorecard]], path: Path | None = None) -> None:
    path = path or README
    text = path.read_text(encoding="utf-8")
    new = replace_block(text, readme_block(cards))
    if new != text:
        path.write_text(new, encoding="utf-8")


def load_scorecard(out_dir: Path) -> Scorecard:
    path = out_dir / SCORES_FILE
    if not path.exists():
        raise FileNotFoundError(f"{path} not found; run `python -m caselens_evals score` first")
    return Scorecard.model_validate_json(path.read_text(encoding="utf-8"))


def save(card: Scorecard, out_dir: Path) -> None:
    (out_dir / SCORES_FILE).write_text(card.model_dump_json(indent=2), encoding="utf-8")
    (out_dir / REPORT_FILE).write_text(render_report(card, out_dir.name), encoding="utf-8")
